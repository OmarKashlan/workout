#!/usr/bin/env node
// Rebuilds sw.js after you change any app file.
// It lists every file the app needs offline and sets a new version, so installed phones download the update.
// Run from the project folder:  node tools/build-sw.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
// Not part of the app itself, so not cached on the phone.
const SKIP_DIRS = new Set(['sync-server', 'tools', 'docs', 'node_modules']);
const SKIP_FILES = new Set(['sw.js', 'README.md', 'LICENSE', '.nojekyll']);

function walk(dir) {
  const out = [];
  const entries = readdirSync(dir, { withFileTypes: true }).filter((e) => !e.name.startsWith('.')).sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const e of entries) if (e.isFile() && !SKIP_FILES.has(e.name)) out.push(relative(ROOT, join(dir, e.name)).split(sep).join('/'));
  for (const e of entries) if (e.isDirectory() && !SKIP_DIRS.has(e.name)) out.push(...walk(join(dir, e.name)));
  return out;
}

const files = walk(ROOT);
const hash = createHash('sha256');
for (const f of files) { hash.update(f); hash.update(readFileSync(join(ROOT, f))); }
const version = hash.digest('hex').slice(0, 10);
const precache = ['./', ...files];

const sw = `// Generated by tools/build-sw.mjs. Version changes whenever any app file changes.
const VERSION = '${version}';
const CORE = 'rul-core-' + VERSION;
const PHOTOS = 'rul-photos';
const PRECACHE = ${JSON.stringify(precache, null, 0).replace(/","/g, '",\n"').replace('[', '[\n').replace(/]$/, '\n]')};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CORE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('rul-core-') && k !== CORE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Exercise photos from Free Exercise DB: keep a copy after the first download.
  if (url.hostname === 'raw.githubusercontent.com') {
    const clean = url.origin + url.pathname;
    if (url.search.includes('thumb')) {
      // Library search thumbnails: use a saved copy if there is one, never store new ones.
      e.respondWith(caches.match(clean).then((hit) => hit || fetch(clean, { mode: 'cors' })));
      return;
    }
    e.respondWith(
      caches.match(clean).then((hit) => hit || fetch(clean, { mode: 'cors' }).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(PHOTOS).then((c) => c.put(clean, copy)); }
        return res;
      }))
    );
    return;
  }

  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    e.respondWith(caches.match('./', { cacheName: CORE }).then((hit) => hit || fetch(req)).catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);
console.log(`sw.js updated: version ${version}, ${precache.length} files cached for offline use.`);
